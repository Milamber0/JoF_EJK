/// The tables in the layout `surface_tables.wgsl` declares: values, permutation, sprites.
pub(crate) fn bytes() -> Vec<u8> {
    let mut bytes = Vec::with_capacity(3 * 256 * 4);
    bytes.extend_from_slice(bytemuck::cast_slice(&NOISE_VALUES));
    bytes.extend_from_slice(bytemuck::cast_slice(&NOISE_PERM));
    bytes.extend_from_slice(bytemuck::cast_slice(&SPRITE_RANDOM));
    bytes
}

/// The buffer every geometry group binds.
pub(crate) fn buffer(device: &wgpu::Device) -> wgpu::Buffer {
    wgpu::util::DeviceExt::create_buffer_init(
        device,
        &wgpu::util::BufferInitDescriptor {
            label: Some("SJK surface tables"),
            contents: &bytes(),
            usage: wgpu::BufferUsages::STORAGE,
        },
    )
}
