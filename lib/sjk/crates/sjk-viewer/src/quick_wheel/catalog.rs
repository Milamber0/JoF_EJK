//! What a quick wheel choice can be: SJK's catalogue of actions, each a console
//! command with its name, its group in the Settings editor, when it counts as in
//! effect and its picture. A page may also hold a console command the player named
//! ([`super::pages::Slot::Custom`]).

/// When a choice counts as in effect, for the dot beside it on the ring.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) enum State {
    /// Never marked.
    None,
    /// The cvar holds this integer.
    Equals(&'static str, i64),
    /// The cvar is on (nonzero).
    On(&'static str),
    /// The cvar is within a hundredth of this number.
    Near(&'static str, f64),
    /// Illuminate's holocron is lit (the client's own state, no cvar holds it:
    /// `toy_illuminate` flips it).
    Illuminate,
}

