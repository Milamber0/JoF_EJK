//! The wire's 162 unit directions (`bytedirs`, `shared/qcommon/q_math.c`): a normal is
//! sent as the index of the nearest one (`DirToByte`) and read back as that direction
//! (`ByteToDir`). Impact events carry surface normals this way.

/// Decode a normal byte exactly as `ByteToDir` does. Values outside
/// the 162-entry range become the zero vector; the wire field itself is 8-bit.
pub fn legacy_byte_to_direction(value: u8) -> [f32; 3] {
    BYTE_DIRECTIONS
        .get(usize::from(value))
        .copied()
        .unwrap_or([0.0; 3])
}

/// Encode a normal with codemp `DirToByte`'s greatest-dot-product search
/// (`shared/qcommon/q_math.c:123-144`).
pub fn legacy_direction_to_byte(direction: [f32; 3]) -> u8 {
    let mut best = 0;
    let mut best_dot = 0.0;
    for (index, candidate) in BYTE_DIRECTIONS.iter().enumerate() {
        let dot = direction
            .into_iter()
            .zip(*candidate)
            .map(|(left, right)| left * right)
            .sum();
        if dot > best_dot {
            best_dot = dot;
            best = index as u8;
        }
    }
    best
}

